#!/usr/bin/env python3
"""Generate P12 Python and JavaScript transport artifacts from the single OpenAPI contract.

Usage:
  python scripts/p12_contract_codegen.py          # write artifacts
  python scripts/p12_contract_codegen.py --check  # fail when any artifact differs

The generator is repository-owned and dependency-free so the Python 3.10 project runtime
and the product-web Node toolchain regenerate byte-identical artifacts.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pprint
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "schemas" / "p12" / "v1" / "openapi.json"
PY_OUT = ROOT / "src" / "quanthus" / "platform" / "p12" / "contract_generated.py"
JS_OUT = ROOT / "product-web" / "src" / "p12" / "contract.generated.js"
DTS_OUT = ROOT / "product-web" / "src" / "p12" / "contract.generated.d.ts"
GENERATOR_VERSION = "p12-contract-codegen.v1"
SUPPORTED = {
    "type",
    "enum",
    "const",
    "pattern",
    "format",
    "minLength",
    "maxLength",
    "minimum",
    "required",
    "properties",
    "additionalProperties",
    "items",
    "anyOf",
    "$ref",
}
HEADER = (
    "Generated by scripts/p12_contract_codegen.py from schemas/p12/v1/openapi.json. Do not edit."
)


def _check_keywords(name: str, schema: dict[str, Any]) -> None:
    unknown = set(schema).difference(SUPPORTED)
    if unknown:
        raise SystemExit(f"{name}: unsupported schema keywords {sorted(unknown)}")
    if schema.get("type") == "object":
        if schema.get("additionalProperties") is not False:
            raise SystemExit(f"{name}: objects must be closed")
        # Optional fields are allowed: required must be a subset of properties.
        # An omitted optional property carries its documented default; present
        # properties are always validated (audit R18 contract compatibility).
        missing_required = set(schema.get("required", [])).difference(
            schema.get("properties", {})
        )
        if missing_required:
            raise SystemExit(f"{name}: required fields not declared {sorted(missing_required)}")
    for key, child in schema.get("properties", {}).items():
        _check_keywords(f"{name}.{key}", child)
    if "items" in schema:
        _check_keywords(f"{name}[]", schema["items"])
    for index, child in enumerate(schema.get("anyOf", [])):
        _check_keywords(f"{name}|{index}", child)


def load() -> dict[str, Any]:
    doc: dict[str, Any] = json.loads(SCHEMA.read_text(encoding="utf-8"))
    for name, schema in doc["components"]["schemas"].items():
        _check_keywords(name, schema)
    return doc


def schema_digest(doc: dict[str, Any]) -> str:
    canonical = json.dumps(doc, ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    return "sha256:" + hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def operations(doc: dict[str, Any]) -> dict[str, dict[str, Any]]:
    result: dict[str, dict[str, Any]] = {}
    for path, item in sorted(doc["paths"].items()):
        for method, op in sorted(item.items()):
            if method == "parameters":
                continue
            request = op.get("requestBody", {}).get("content", {}).get("application/json", {})
            response = op["responses"]["200"]["content"]["application/json"]["schema"]
            result[op["operationId"]] = {
                "method": method.upper(),
                "path": path,
                "permission": op["x-quanthus-permission"],
                "request": request.get("schema", {}).get("$ref", "").rsplit("/", 1)[-1] or None,
                "response": response["$ref"].rsplit("/", 1)[-1],
            }
    return result


def render_python(doc: dict[str, Any]) -> str:
    version = doc["components"]["schemas"]["SchemaVersion"]["const"]
    parts = [
        f'"""{HEADER}"""',
        "",
        "# ruff: noqa: E501",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        f"GENERATOR_VERSION = {GENERATOR_VERSION!r}",
        f"SCHEMA_VERSION = {version!r}",
        f"SCHEMA_DIGEST = {schema_digest(doc)!r}",
        "OPERATIONS: dict[str, dict[str, Any]] = "
        + pprint.pformat(operations(doc), width=99, sort_dicts=True),
        "REASON_TEXTS: dict[str, str] = "
        + pprint.pformat(doc["x-quanthus-reason-texts"], width=99, sort_dicts=True),
        "LABELS: dict[str, dict[str, str]] = "
        + pprint.pformat(doc["x-quanthus-labels"], width=99, sort_dicts=True),
        "COMPONENTS: dict[str, Any] = "
        + pprint.pformat(doc["components"]["schemas"], width=99, sort_dicts=True),
        "",
    ]
    return "\n".join(parts)


def _js(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True)


def render_js(doc: dict[str, Any]) -> str:
    version = doc["components"]["schemas"]["SchemaVersion"]["const"]
    parts = [
        f"// {HEADER}",
        f"export const GENERATOR_VERSION = {json.dumps(GENERATOR_VERSION)}",
        f"export const P12_SCHEMA_VERSION = {json.dumps(version)}",
        f"export const P12_SCHEMA_DIGEST = {json.dumps(schema_digest(doc))}",
        f"export const OPERATIONS = Object.freeze({_js(operations(doc))})",
        f"export const REASON_TEXTS = Object.freeze({_js(doc['x-quanthus-reason-texts'])})",
        f"export const LABELS = Object.freeze({_js(doc['x-quanthus-labels'])})",
        f"export const COMPONENTS = Object.freeze({_js(doc['components']['schemas'])})",
        "",
    ]
    return "\n".join(parts)


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(_ts_type(item) for item in schema["anyOf"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "string":
        return "string"
    if kind == "integer":
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        inner = _ts_type(schema["items"])
        return f"Array<{inner}>"
    raise SystemExit(f"cannot render TypeScript type for {schema}")


def render_dts(doc: dict[str, Any]) -> str:
    lines = [f"// {HEADER}", ""]
    for name, schema in sorted(doc["components"]["schemas"].items()):
        if schema.get("type") == "object":
            lines.append(f"export interface {name} {{")
            for key, child in sorted(schema["properties"].items()):
                lines.append(f"  {key}: {_ts_type(child)}")
            lines.append("}")
        else:
            note = f" // pattern {schema['pattern']}" if "pattern" in schema else ""
            lines.append(f"export type {name} = {_ts_type(schema)}{note}")
        lines.append("")
    lines.append("export declare const P12_SCHEMA_VERSION: SchemaVersion")
    lines.append("export declare const REASON_TEXTS: Readonly<Record<ReasonCode, string>>")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    doc = load()
    outputs = {PY_OUT: render_python(doc), JS_OUT: render_js(doc), DTS_OUT: render_dts(doc)}
    drift = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != content:
                drift.append(str(path.relative_to(ROOT)))
        elif current != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if drift:
        print(json.dumps({"p12_contract_drift": drift}), file=sys.stderr)
        return 1
    print(
        json.dumps(
            {"p12_contract": "check" if args.check else "written", "digest": schema_digest(doc)}
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
