"""Scale-explicit, evidence-retaining references; no acquisition, labels or parameter search.

Inputs are already supplied DailyInput objects. Two formal Fact families are built once per
batch. Opinions are externally supplied, never generated by this module. Independent verification
reconstructs retained evidence in an explicit cold-readback mode, not in each reviewer view.
"""
from __future__ import annotations

