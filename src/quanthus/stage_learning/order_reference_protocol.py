import hashlib
import json
import re
import time
from collections import Counter
from collections.abc import Callable, Mapping, Sequence
from dataclasses import asdict, fields, replace
from datetime import date, datetime, timezone
from decimal import Decimal
from pathlib import Path
from typing import Any

from quanthus.policy import find_project_root
from quanthus.structure_order_facts import (
    RANGE_CENTER_SHIFT,
    RANGE_WIDTH,
    WIDTH_CHANGE,
    build_structure_order_facts,
)
from quanthus.structure_trend_evolution import (
    DIRECTIONAL_EFFICIENCY,
    build_trend_evolution_facts,
)
from quanthus.structure_v2_inputs import DailyInput, InputPolicy, admit_daily, canonical, digest

PROTOCOL_PATH = "config/stage-learning/order-reference-protocol.v1.json"
PROTOCOL_DIGEST = "sha256:927edd8451c9db9adb0ac06e24dcbc55d11e1ac82aac87123a4d9627557eaf1e"
EVIDENCE_SCHEMA = "quanthus.stage-order-reference-evidence.v1"
REVIEW_SCHEMA = "quanthus.stage-order-reference-opinion.v1"
ARTIFACT_SCHEMA = "quanthus.stage-order-reference-artifact.v1"
ROLES = ("short_term", "fund")
MAX_BYTES = 33554432
FILES = ("evidence.json", "reviews.json", "resolved.json", "summary.json")
_REVISION = re.compile(r"^[0-9a-f]{40}$")


class OrderReferenceError(ValueError):
    """A bounded reference input, provenance or artifact is invalid."""


def _plain(value: Any) -> Any:
    return json.loads(canonical(value))


def _keys(value: Any, expected: set[str], label: str) -> None:
    if not isinstance(value, dict) or set(value) != expected:
        raise OrderReferenceError(f"{label}_fields_differ")


def _text(value: Any, label: str, limit: int = 2000) -> None:
    if not isinstance(value, str) or not value.strip() or len(value) > limit:
        raise OrderReferenceError(f"{label}_invalid")


def _validate_protocol_value(
    value: Mapping[str, Any], *, expected_digest: str, root: Path,
) -> dict[str, Any]:
    protocol = dict(value)
    if digest(protocol) != expected_digest:
        raise OrderReferenceError("protocol_drift_requires_new_version")
    for contract in protocol["fact_contracts"].values():
        fact = json.loads((root / contract["path"]).read_text(encoding="utf-8"))
        if digest(fact) != contract["digest"]:
            raise OrderReferenceError("formal_fact_contract_drift")
    try:
        history_start = date.fromisoformat(protocol["history_start"])
        case_start = date.fromisoformat(protocol["case_start"])
        development_end = date.fromisoformat(protocol["development_end"])
    except (KeyError, TypeError, ValueError) as exc:
        raise OrderReferenceError("protocol_time_scope_invalid") from exc
    if not history_start <= case_start <= development_end:
        raise OrderReferenceError("protocol_time_scope_invalid")
    bounds = protocol.get("bounds")
    if not isinstance(bounds, Mapping) or set(bounds) != {
        "max_cases",
        "max_source_rows",
        "max_artifact_bytes",
    }:
        raise OrderReferenceError("protocol_bounds_invalid")
    if any(type(bounds[key]) is not int or bounds[key] <= 0 for key in bounds):
        raise OrderReferenceError("protocol_bounds_invalid")
    if bounds["max_artifact_bytes"] > MAX_BYTES:
        raise OrderReferenceError("protocol_artifact_budget_exceeds_hard_limit")
    return protocol


def load_protocol(root: Path | None = None) -> dict[str, Any]:
    root = root or find_project_root()
    value = json.loads((root / PROTOCOL_PATH).read_text(encoding="utf-8"))
    return _validate_protocol_value(value, expected_digest=PROTOCOL_DIGEST, root=root)


def load_protocol_contract(
    path: str, expected_digest: str, root: Path | None = None,
) -> dict[str, Any]:
    root = root or find_project_root()
    try:
        value = json.loads((root / path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise OrderReferenceError("protocol_unreadable") from exc
    return _validate_protocol_value(value, expected_digest=expected_digest, root=root)


def _measurement(item: Any | None) -> dict[str, Any]:
    if item is None:
        return {"value": None, "revision_id": None, "reason": "fact_unavailable"}
    return _plain({
        "value": item.value,
        "revision_id": item.identity.revision_id,
        "reason": item.availability_reason,
    })


def build_evidence(
    rows: Sequence[DailyInput],
    case_keys: Sequence[tuple[str, date]],
    policy: InputPolicy,
    *,
    code_revision: str,
    source_kind: str,
    sampling_strata: Mapping[tuple[str, date], str] | None = None,
    progress: Callable[[dict], None] | None = None,
    protocol_override: Mapping[str, Any] | None = None,
    protocol_digest: str | None = None,
) -> dict[str, Any]:
    """Materialize one shared source/Fact closure and per-T views, without fetching data."""
    started = time.perf_counter()
    last_stage = started

    def observed(stage: str, count: int, byte_count: int = 0) -> None:
        nonlocal last_stage
        now = time.perf_counter()
        if progress is not None:
            progress({"stage": stage, "elapsed_seconds": now - started,
                      "stage_elapsed_seconds": now - last_stage,
                      "rows": count, "bytes": byte_count, "disposition": "built_once"})
        last_stage = now

    if protocol_override is None:
        protocol = load_protocol()
        active_protocol_digest = PROTOCOL_DIGEST
    else:
        if not isinstance(protocol_digest, str) or not protocol_digest.startswith("sha256:"):
            raise OrderReferenceError("explicit_protocol_digest_required")
        protocol = _validate_protocol_value(
            protocol_override,
            expected_digest=protocol_digest,
            root=find_project_root(),
        )
        active_protocol_digest = protocol_digest
    if not isinstance(code_revision, str) or not _REVISION.fullmatch(code_revision):
        raise OrderReferenceError("exact_code_revision_required")
    if source_kind not in {"synthetic_fixture", "retrospective_development"}:
        raise OrderReferenceError("source_kind_invalid")
    if not rows or len(rows) > protocol["bounds"]["max_source_rows"]:
        raise OrderReferenceError("source_row_budget")
    if not case_keys or len(case_keys) > protocol["bounds"]["max_cases"]:
        raise OrderReferenceError("case_budget")
    if len(set(case_keys)) != len(case_keys):
        raise OrderReferenceError("duplicate_case")
    if policy.spec_digest != active_protocol_digest:
        raise OrderReferenceError("input_policy_protocol_mismatch")
    keys = sorted(case_keys)
    strata = dict(sampling_strata or {key: "unspecified" for key in keys})
    if set(strata) != set(keys) or any(
        value not in {"unspecified", "representative", "boundary", "enriched", "synthetic_fixture"}
        for value in strata.values()
    ):
        raise OrderReferenceError("sampling_stratum_scope_mismatch")
    if set(policy.security_codes) != {code for code, _ in keys}:
        raise OrderReferenceError("case_security_denominator_mismatch")
    case_start = date.fromisoformat(protocol["case_start"])
    development_end = date.fromisoformat(protocol["development_end"])
    history_start = date.fromisoformat(protocol["history_start"])
    if any(
        type(day) is not date or not case_start <= day <= development_end
        for _, day in keys
    ):
        raise OrderReferenceError("case_outside_development")
    ordered = sorted(rows, key=lambda row: (row.security_code, row.market_date))
    attempts = {(row.security_code, row.market_date): row for row in ordered}
    if len(attempts) != len(rows):
        raise OrderReferenceError("duplicate_security_session")
    if not set(keys) <= set(attempts):
        raise OrderReferenceError("case_source_row_missing")
    last_day = max(day for _, day in keys)
    normalized = []
    for row in ordered:
        if not history_start <= row.market_date <= last_day:
            raise OrderReferenceError("source_outside_declared_time_scope")
        if row.security_code not in policy.security_codes:
            raise OrderReferenceError("source_security_outside_scope")
        if (row.cutoff.tzinfo is None or row.cutoff.utcoffset() is None
                or row.result_as_of > row.cutoff):
            raise OrderReferenceError("source_cutoff_invalid")
        # A caller's later use time is not the business observation identity.
        normalized.append(replace(row, cutoff=row.result_as_of))
    admissions = tuple(admit_daily(row, policy) for row in normalized)
    observed("admission", len(admissions))
    start, end = min(day for _, day in keys), last_day
    trend = build_trend_evolution_facts(admissions, report_start=start, report_end=end)
    observed("trend_facts", len(trend.measurements))
    order = build_structure_order_facts(admissions, report_start=start, report_end=end)
    observed("order_facts", len(order.measurements))
    measurements = {
        (m.security_code, m.market_date, m.concept_id, m.window_sessions,
         m.comparison_window_sessions): m
        for family in (trend, order) for m in family.measurements
    }
    target_admissions = {item.key: item for item in admissions}
    availability = {
        (name, item.security_code, item.market_date): item.reason
        for name, family in (("trend", trend), ("order", order))
        for item in family.availability
    }
    source_rows = {}
    row_refs = {}
    for row in normalized:
        encoded = canonical(asdict(row))
        ref = _sha(encoded)
        source_rows[ref] = json.loads(encoded)
        row_refs[(row.security_code, row.market_date)] = ref
    by_security: dict[str, list[DailyInput]] = {}
    for row in normalized:
        by_security.setdefault(row.security_code, []).append(row)
    cases = []
    for code, day in keys:
        attempt = target_admissions[(code, day)]
        current = attempt.row
        history = [row for row in by_security[code] if row.market_date <= day][-61:]

        def measure(
            concept: str, window: int, comparison: int | None = None,
            security: str = code, result_day: date = day,
        ) -> dict:
            key = (security, result_day, concept, window, comparison)
            return _measurement(measurements.get(key))

        primary = {
            "directional_efficiency": measure(DIRECTIONAL_EFFICIENCY, 20),
            "range_width": measure(RANGE_WIDTH, 20),
            "width_change": measure(WIDTH_CHANGE, 20, 20),
            "center_shift": measure(RANGE_CENTER_SHIFT, 20, 20),
        }
        recent = {
            "width_change": measure(WIDTH_CHANGE, 10, 10),
            "center_shift": measure(RANGE_CENTER_SHIFT, 10, 10),
        }
        payload = _plain({
            "protocol_digest": active_protocol_digest,
            "code_revision": code_revision,
            "policy_digest": digest(policy),
            "source_kind": source_kind, "sampling_stratum": strata[(code, day)],
            "security_code": code, "security_id": current.security_id,
            "listing_id": current.listing_id, "market_date": day,
            "result_as_of": current.result_as_of, "coordinate_ref": current.coordinate_ref,
            "knowledge_view": "retrospective",
            "primary_window_sessions": 20, "recent_window_sessions": 10,
            "history_refs": [row_refs[(row.security_code, row.market_date)] for row in history],
            "primary": primary, "recent": recent,
            "primary_available": attempt.admitted and all(
                item["value"] is not None for item in primary.values()
            ),
            "recent_available": attempt.admitted and all(
                item["value"] is not None for item in recent.values()
            ),
            "input_reason": attempt.reason,
            "availability_reasons": {
                name: availability.get((name, code, day), "fact_unavailable")
                for name in ("trend", "order")
            },
        })
        cases.append({"case_id": digest(payload), **payload})
    result = _plain({
        "schema_version": EVIDENCE_SCHEMA, "protocol": protocol,
        "input_policy": policy, "source_kind": source_kind, "code_revision": code_revision,
        "source_rows": source_rows, "cases": cases,
    })
    byte_count = len(canonical(result))
    if byte_count > protocol["bounds"]["max_artifact_bytes"]:
        raise OrderReferenceError("evidence_size_budget")
    observed("case_packets", len(cases), byte_count)
    return result


def _decode_rows(
    evidence: dict, *, max_source_rows: int = 20000,
) -> tuple[list[DailyInput], InputPolicy]:
    rows = []
    stored = evidence["source_rows"]
    if not isinstance(stored, dict) or not 0 < len(stored) <= max_source_rows:
        raise OrderReferenceError("source_row_budget")
    names = {item.name for item in fields(DailyInput)}
    try:
        for ref, record in stored.items():
            _keys(record, names, "source_row")
            if digest(record) != ref:
                raise OrderReferenceError("source_member_digest_mismatch")
            values = dict(record)
            values["market_date"] = date.fromisoformat(values["market_date"])
            values["cutoff"] = datetime.fromisoformat(values["cutoff"])
            for key in ("high", "low", "close", "volume"):
                values[key] = None if values[key] is None else Decimal(values[key])
            rows.append(DailyInput(**values))
        raw_policy = dict(evidence["input_policy"])
        _keys(raw_policy, {item.name for item in fields(InputPolicy)}, "input_policy")
        raw_policy["security_codes"] = tuple(raw_policy["security_codes"])
        return rows, InputPolicy(**raw_policy)
    except (TypeError, KeyError, ValueError) as exc:
        raise OrderReferenceError(f"stored_source_invalid:{exc}") from exc


def validate_evidence(
    evidence: dict, *, expected_protocol_digest: str = PROTOCOL_DIGEST,
) -> None:
    """Explicit independent reconstruction; intentionally separate from ordinary packet views."""
    _keys(evidence, {
        "schema_version", "protocol", "input_policy", "source_kind", "code_revision",
        "source_rows", "cases",
    }, "evidence")
    if (
        evidence["schema_version"] != EVIDENCE_SCHEMA
        or digest(evidence["protocol"]) != expected_protocol_digest
    ):
        raise OrderReferenceError("evidence_protocol_mismatch")
    protocol = _validate_protocol_value(
        evidence["protocol"],
        expected_digest=expected_protocol_digest,
        root=find_project_root(),
    )
    bounds = protocol["bounds"]
    if (
        not isinstance(evidence["cases"], list)
        or not 0 < len(evidence["cases"]) <= bounds["max_cases"]
    ):
        raise OrderReferenceError("case_budget")
    rows, policy = _decode_rows(
        evidence, max_source_rows=bounds["max_source_rows"]
    )
    try:
        keys = [(item["security_code"], date.fromisoformat(item["market_date"]))
                for item in evidence["cases"]]
        rebuilt = build_evidence(
            rows, keys, policy, code_revision=evidence["code_revision"],
            source_kind=evidence["source_kind"],
            sampling_strata={
                (item["security_code"], date.fromisoformat(item["market_date"])):
                item["sampling_stratum"] for item in evidence["cases"]
            },
            protocol_override=protocol,
            protocol_digest=expected_protocol_digest,
        )
    except (KeyError, TypeError, ValueError) as exc:
        raise OrderReferenceError(f"case_reconstruction_invalid:{exc}") from exc
    if canonical(rebuilt) != canonical(evidence):
        raise OrderReferenceError("evidence_reconstruction_mismatch")


def reviewer_view(evidence: dict, case_id: str) -> dict:
    """Expand only this case's T-only closure from an already verified/locally built batch."""
    found = [item for item in evidence["cases"] if item["case_id"] == case_id]
    if len(found) != 1:
        raise OrderReferenceError("review_case_missing_or_duplicate")
    case = found[0]
    if digest({key: value for key, value in case.items() if key != "case_id"}) != case_id:
        raise OrderReferenceError("case_digest_mismatch")
    history = []
    for ref in case["history_refs"]:
        row = evidence["source_rows"].get(ref)
        if row is None or digest(row) != ref or row["market_date"] > case["market_date"]:
            raise OrderReferenceError("review_history_mismatch_or_future")
        history.append(row)
    return _plain({
        "case": case, "price_history": history, "profile": evidence["protocol"]["profile"],
    })


def _opinion(raw: dict, case: dict) -> dict:
    expected = {
        "schema_version", "case_id", "protocol_digest", "reviewer_id", "role", "provenance",
        "primary_window_sessions", "recent_window_sessions", "primary", "recent",
        "support_refs", "contradiction_refs", "reason", "unknowns",
    }
    _keys(raw, expected, "opinion")
    if (raw["schema_version"] != REVIEW_SCHEMA or raw["case_id"] != case["case_id"]
            or raw["protocol_digest"] != PROTOCOL_DIGEST):
        raise OrderReferenceError("opinion_binding_mismatch")
    if (type(raw["primary_window_sessions"]) is not int or raw["primary_window_sessions"] != 20
            or type(raw["recent_window_sessions"]) is not int
            or raw["recent_window_sessions"] != 10):
        raise OrderReferenceError("opinion_scale_mismatch")
    if raw["role"] not in ROLES:
        raise OrderReferenceError("opinion_role_invalid")
    _text(raw["reviewer_id"], "reviewer_id", 200)
    _text(raw["reason"], "opinion_reason")
    provenance = raw["provenance"]
    _keys(provenance, {"kind", "origin_id", "session_id"}, "provenance")
    if provenance["kind"] not in {"self_simulated", "deterministic_policy", "external_ai", "human"}:
        raise OrderReferenceError("provenance_kind_invalid")
    for key in ("origin_id", "session_id"):
        _text(provenance[key], key, 200)
    _keys(raw["primary"], {"stage_0", "stage_2"}, "primary_opinion")
    if any(value not in ("TRUE", "FALSE", "UNKNOWN") for value in raw["primary"].values()):
        raise OrderReferenceError("primary_truth_value_invalid")
    _keys(raw["recent"], {"width", "center"}, "recent_opinion")
    width = {"CONTRACTING", "EXPANDING", "STABLE", "UNKNOWN", "UNAVAILABLE"}
    center = {"STABLE", "SHIFTING", "UNKNOWN", "UNAVAILABLE"}
    if raw["recent"]["width"] not in width or raw["recent"]["center"] not in center:
        raise OrderReferenceError("recent_condition_invalid")
    for key in ("support_refs", "contradiction_refs", "unknowns"):
        if not isinstance(raw[key], list) or any(not isinstance(v, str) for v in raw[key]):
            raise OrderReferenceError("opinion_references_invalid")
        if len(raw[key]) > 100 or len(set(raw[key])) != len(raw[key]):
            raise OrderReferenceError("opinion_references_duplicate_or_oversized")
    for reason in raw["unknowns"]:
        _text(reason, "unknown_reason")
    available_refs = set(case["history_refs"]) | {
        item["revision_id"] for area in ("primary", "recent") for item in case[area].values()
        if item["revision_id"] is not None
    }
    if not set(raw["support_refs"] + raw["contradiction_refs"]) <= available_refs:
        raise OrderReferenceError("opinion_evidence_reference_mismatch")
    if "TRUE" in raw["primary"].values() and not raw["support_refs"]:
        raise OrderReferenceError("positive_opinion_requires_evidence")
    if not case["primary_available"] and set(raw["primary"].values()) != {"UNKNOWN"}:
        raise OrderReferenceError("unavailable_primary_cannot_assert")
    if not case["recent_available"] and set(raw["recent"].values()) != {"UNAVAILABLE"}:
        raise OrderReferenceError("unavailable_recent_cannot_assert")
    if case["recent_available"] and "UNAVAILABLE" in raw["recent"].values():
        raise OrderReferenceError("available_recent_cannot_be_missing")
    uncertain = ("UNKNOWN" in raw["primary"].values() or "UNKNOWN" in raw["recent"].values()
                 or not case["primary_available"] or not case["recent_available"])
    if uncertain and not raw["unknowns"]:
        raise OrderReferenceError("unknown_opinion_requires_reason")
    return _plain(raw)


def resolve_opinions(evidence: dict, opinions: Sequence[dict]) -> tuple[list[dict], dict]:
    """Resolve external claims; preserve disagreement without majority or adjudication."""
    cases = {case["case_id"]: case for case in evidence["cases"]}
    if len(cases) != len(evidence["cases"]) or len(opinions) != 2 * len(cases):
        raise OrderReferenceError("opinion_case_denominator_mismatch")
    indexed: dict[tuple[str, str], dict] = {}
    reviewers: dict[str, str] = {}
    origins: set[str] = set()
    source_kinds: set[str] = set()
    for raw in opinions:
        if not isinstance(raw, dict) or raw.get("case_id") not in cases:
            raise OrderReferenceError("opinion_case_unknown")
        item = _opinion(raw, cases[raw["case_id"]])
        key = (item["case_id"], item["role"])
        if key in indexed:
            raise OrderReferenceError("duplicate_opinion")
        indexed[key] = item
        identity = digest({
            "reviewer_id": item["reviewer_id"],
            "origin_id": item["provenance"]["origin_id"], "kind": item["provenance"]["kind"],
        })
        prior = reviewers.setdefault(item["role"], identity)
        if identity != prior:
            raise OrderReferenceError("reviewer_identity_changed_within_ledger")
        origins.add(item["provenance"]["origin_id"])
        source_kinds.add(item["provenance"]["kind"])
    resolved = []
    for case_id, case in sorted(cases.items()):
        if any((case_id, role) not in indexed for role in ROLES):
            raise OrderReferenceError("both_semantic_roles_required")
        left, right = (indexed[(case_id, role)] for role in ROLES)
        if left["reviewer_id"] == right["reviewer_id"]:
            raise OrderReferenceError("reviewer_cannot_impersonate_two_roles")
        if not case["primary_available"]:
            status = "INPUT_UNAVAILABLE"
        elif any(set(item["primary"].values()) == {"TRUE"} for item in (left, right)):
            status = "RULE_CONFLICT"
        elif left["primary"] != right["primary"] or "UNKNOWN" in left["primary"].values():
            status = "AMBIGUOUS"
        elif left["primary"]["stage_0"] == "TRUE":
            status = "STAGE_0"
        elif left["primary"]["stage_2"] == "TRUE":
            status = "STAGE_2"
        else:
            status = "NEITHER"
        resolved.append({
            "case_id": case_id, "primary_reference": status,
            "recent_agreement": left["recent"] == right["recent"],
            "opinion_digests": [digest(item) for item in (left, right)],
        })
    summary = {
        "status": "REFERENCE_MECHANISM_ONLY",
        "case_count": len(cases), "opinion_count": len(opinions),
        "primary_reference_counts": dict(sorted(Counter(
            item["primary_reference"] for item in resolved
        ).items())),
        "recent_disagreement_count": sum(not item["recent_agreement"] for item in resolved),
        "security_count": len({item["security_code"] for item in cases.values()}),
        "date_count": len({item["market_date"] for item in cases.values()}),
        "source_kind": evidence["source_kind"],
        "sampling_stratum_counts": dict(sorted(Counter(
            case["sampling_stratum"] for case in cases.values()
        ).items())),
        "reference_counts_by_stratum": {
            stratum: dict(sorted(Counter(
                item["primary_reference"] for item in resolved
                if cases[item["case_id"]]["sampling_stratum"] == stratum
            ).items())) for stratum in sorted({c["sampling_stratum"] for c in cases.values()})
        },
        "review_source_kinds": sorted(source_kinds), "distinct_origin_count": len(origins),
        "human_expert_validated": False, "independent_validation": False,
        "external_source_verified": False, "market_reference_validated": False,
        "parameter_search_authorized": False, "official_label_authorized": False,
        "primary_stage": None,
    }
    return resolved, summary


def _sha(payload: bytes) -> str:
    return "sha256:" + hashlib.sha256(payload).hexdigest()


def _no_links(path: Path) -> None:
    if any(item.is_symlink() for item in (path, *path.parents)):
        raise OrderReferenceError("artifact_symlink_forbidden")


def publish_bundle(
    target: Path, evidence: dict, opinions: Sequence[dict], *, generated_at: datetime | None = None,
) -> dict:
    """Seal all evidence and original opinions. Existing/partial bundles are never overwritten."""
    _no_links(target)
    if target.exists():
        raise OrderReferenceError("immutable_artifact_exists")
    # This is an explicit publisher audit, not another consumer's materialization.
    validate_evidence(evidence)
    resolved, summary = resolve_opinions(evidence, opinions)
    clock = generated_at or datetime.now(timezone.utc)
    if clock.tzinfo is None or clock.utcoffset() is None:
        raise OrderReferenceError("generation_clock_timezone_missing")
    values = (evidence, sorted(opinions, key=lambda item: (item["case_id"], item["role"])),
              resolved, summary)
    payloads = {name: canonical(value) for name, value in zip(FILES, values, strict=True)}
    if sum(map(len, payloads.values())) > MAX_BYTES:
        raise OrderReferenceError("artifact_size_budget")
    manifest = {
        "schema_version": ARTIFACT_SCHEMA,
        "generated_at": _plain(clock),
        "protocol_digest": PROTOCOL_DIGEST,
        "files": {name: _sha(payload) for name, payload in payloads.items()},
    }
    encoded_manifest = canonical(manifest)
    if sum(map(len, payloads.values())) + len(encoded_manifest) + 72 > MAX_BYTES:
        raise OrderReferenceError("artifact_size_budget")
    target.mkdir(parents=True, exist_ok=False)
    for name, payload in payloads.items():
        with (target / name).open("xb") as stream:
            stream.write(payload)
    with (target / "manifest.json").open("xb") as stream:
        stream.write(encoded_manifest)
    with (target / "READY").open("x", encoding="ascii") as stream:
        stream.write(_sha(encoded_manifest) + "\n")
    return {"root": str(target), "manifest_sha256": _sha(encoded_manifest), **summary}


def _unique_object(pairs: list[tuple[str, Any]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise OrderReferenceError("duplicate_json_field")
        result[key] = value
    return result


def verify_bundle(target: Path) -> dict:
    """Cold reconstruction from the sealed package, not merely a checksum or claimed status."""
    _no_links(target)
    expected = {*FILES, "manifest.json", "READY"}
    try:
        if not target.is_dir() or {p.name for p in target.iterdir()} != expected:
            raise OrderReferenceError("artifact_inventory_mismatch")
        for name in expected:
            file = target / name
            if file.is_symlink() or not file.is_file():
                raise OrderReferenceError("artifact_regular_files_required")
        if sum((target / name).stat().st_size for name in expected) > MAX_BYTES:
            raise OrderReferenceError("artifact_size_budget")
        payloads = {}
        consumed = 0
        for name in sorted(expected):
            with (target / name).open("rb") as stream:
                payloads[name] = stream.read(MAX_BYTES - consumed + 1)
            consumed += len(payloads[name])
            if consumed > MAX_BYTES:
                raise OrderReferenceError("artifact_size_budget")
        if payloads["READY"].decode("ascii").strip() != _sha(payloads["manifest.json"]):
            raise OrderReferenceError("ready_manifest_mismatch")
        manifest = json.loads(payloads["manifest.json"], object_pairs_hook=_unique_object)
        _keys(manifest, {"schema_version", "generated_at", "protocol_digest", "files"}, "manifest")
        if (manifest["schema_version"] != ARTIFACT_SCHEMA
                or manifest["protocol_digest"] != PROTOCOL_DIGEST):
            raise OrderReferenceError("artifact_schema_or_protocol_mismatch")
        clock = datetime.fromisoformat(manifest["generated_at"])
        if clock.tzinfo is None or clock.utcoffset() is None:
            raise OrderReferenceError("generation_clock_timezone_missing")
        if manifest["files"] != {name: _sha(payloads[name]) for name in FILES}:
            raise OrderReferenceError("artifact_file_digest_mismatch")
        evidence, opinions, resolved, summary = (
            json.loads(payloads[name], object_pairs_hook=_unique_object) for name in FILES
        )
        validate_evidence(evidence)
        expected_resolved, expected_summary = resolve_opinions(evidence, opinions)
        if (canonical(expected_resolved) != canonical(resolved)
                or canonical(expected_summary) != canonical(summary)):
            raise OrderReferenceError("reference_resolution_reconstruction_mismatch")
        return {"verified": True, "mode": "independent_reconstruction",
                "manifest_sha256": _sha(payloads["manifest.json"]), **summary}
    except (OSError, KeyError, TypeError, ValueError) as exc:
        raise OrderReferenceError(f"artifact_invalid:{exc}") from exc


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "artifact", type=Path, help="Existing reference bundle to verify; no data run",
    )
    args = parser.parse_args(argv)
    try:
        print(json.dumps(verify_bundle(args.artifact), sort_keys=True))
    except OrderReferenceError as exc:
        print(json.dumps({"verified": False, "reason": str(exc)}))
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
